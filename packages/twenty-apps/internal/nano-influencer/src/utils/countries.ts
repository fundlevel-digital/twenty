export const normalizeCountry = (value: string | undefined): string | null => {
  const normalized = value?.trim().toLowerCase();
  if (!normalized) return null;
  const aliases: Record<string, string> = {
    uk: 'GB',
    usa: 'US',
    'united states of america': 'US',
    turkey: 'TR',
    'south korea': 'KR',
    'north korea': 'KP',
    russia: 'RU',
    vietnam: 'VN',
    taiwan: 'TW',
    'czech republic': 'CZ',
  };
  return (
    aliases[normalized] ??
    COUNTRIES.find(
      (country) =>
        country.value.toLowerCase() === normalized ||
        country.label.toLowerCase() === normalized,
    )?.value ??
    null
  );
};
